#!/usr/bin/env node
/**
 * Mirror an existing site/data/archive.json's media into R2 — no X API calls.
 *
 * Separate from sync.mjs on purpose: re-running the sync to (re)upload images
 * would spend X API credits for no reason, and images need re-mirroring far
 * more often than the follower list changes (new domain, failed downloads,
 * a bucket that was wiped). This only touches R2 + the local JSON.
 *
 *   node scripts/mirror-media.mjs              # download + upload + rewrite URLs
 *   node scripts/mirror-media.mjs --dry-run    # show what would be mirrored
 *   node scripts/mirror-media.mjs --concurrency 12
 *
 * Idempotent: objects already in the bucket are skipped (one HEAD each), and
 * records whose URLs already point at R2 are left alone.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { mediaPlan } from './lib/archive.mjs';
import { R2Bucket, mirrorMedia } from './lib/r2.mjs';
import { hashAssets } from './lib/hash-assets.mjs';
import { DATA_FILE, SITE, loadEnv, parseArgs, log, warn, R2_CREDS } from './lib/config.mjs';

const args = parseArgs();
const DRY = !!args['dry-run'];
const env = loadEnv();
const r2 = R2_CREDS(env);

if (!r2.accountId || !r2.accessKeyId || !r2.secretKey || !r2.bucket) {
  console.error('✘ 缺少 R2 配置：CLOUDFLARE_ACCOUNT_ID / R2_BUCKET / R2_ACCESS_KEY_ID / R2_SECRET_ACCESS_KEY');
  process.exit(1);
}
if (!r2.publicDomain) {
  warn('⚠ R2_PUBLIC_DOMAIN 为空——镜像后前端拿不到图片域名，先把它填成 https://img.<域>');
}

const records = JSON.parse(readFileSync(DATA_FILE, 'utf8'));
log(`记录 ${records.length} 条`);

// Plan from the URLs already stored in the archive (twimg → re-host; anything
// already pointing at /media/... is skipped as already-mirrored).
let planned = 0;
for (const r of records) {
  const plan = mediaPlan(r.id, { profile_image_url: r.avatar_url, profile_banner_url: r.cover_url });
  r._plan_avatar = plan.avatar;
  r._plan_cover = plan.cover;
  if (plan.avatar?.rehost) planned++;
  if (plan.cover?.rehost) planned++;
}
log(`需要镜像的对象：${planned}`);

if (DRY) {
  const sample = records.slice(0, 3).map((r) => ({ id: r.id, avatar: r._plan_avatar?.key, cover: r._plan_cover?.key }));
  log('  --dry-run：不下载、不上传、不落盘');
  log('  示例：' + JSON.stringify(sample, null, 1));
  process.exit(0);
}

const bucket = new R2Bucket({ ...r2, log: (m) => log('  ' + m) });
const t0 = Date.now();
const result = await mirrorMedia({
  bucket, records, concurrency: Number(args.concurrency || 8), log: (m) => log(m),
});
log(`\n上传 ${result.uploaded} · 跳过 ${result.skipped} · 失败 ${result.failed.length} · 用时 ${((Date.now() - t0) / 1000).toFixed(1)}s`);

// Rewrite the record URLs to the R2 paths the mirror actually produced.
let rewritten = 0;
for (const r of records) {
  for (const kind of ['avatar', 'cover']) {
    const url = result.rewrites.get(`${r.id}:${kind}`);
    if (url) { r[kind === 'avatar' ? 'avatar_url' : 'cover_url'] = url; rewritten++; }
  }
  delete r._plan_avatar;
  delete r._plan_cover;
}
log(`改写 URL：${rewritten}`);

writeFileSync(DATA_FILE, JSON.stringify(records));
log(`✔ 已写入 ${DATA_FILE.split('/').slice(-3).join('/')}`);

// The site config carries the R2 domain the frontend must prefix onto every
// `/media/...` URL. sync.mjs writes it too, but mirroring can run on an archive
// that was synced before R2 existed — leaving the domain empty makes the browser
// request images from the page origin and 404. Keep it in step here.
const runtimePath = resolve(SITE, 'runtime-config.json');
const prevCfg = existsSync(runtimePath) ? JSON.parse(readFileSync(runtimePath, 'utf8')) : {};
const generatedAt = new Date().toISOString();
const cfg = {
  r2_public_domain: r2.publicDomain || prevCfg.r2_public_domain || '',
  owner_handle: prevCfg.owner_handle || '',
  generated_at: generatedAt,
};
writeFileSync(runtimePath, JSON.stringify(cfg, null, 2) + '\n');
writeFileSync(resolve(SITE, 'env-config.js'),
  `/* Auto-generated by scripts/mirror-media.mjs — do not edit by hand. */\n` +
  `window.__ENV__ = Object.freeze(${JSON.stringify({
    R2_PUBLIC_DOMAIN: cfg.r2_public_domain, OWNER_HANDLE: cfg.owner_handle, GENERATED_AT: cfg.generated_at,
  }, null, 2)});\n`);
log(`✔ 站点配置已更新：R2_PUBLIC_DOMAIN=${cfg.r2_public_domain || '(空!)'}`);
const h = hashAssets();
log(h.changed ? `✔ 资源已指纹化：${JSON.stringify(h.hashes)}` : '  资源指纹无变化');

if (result.failed.length) {
  const byReason = {};
  for (const f of result.failed) byReason[f.error] = (byReason[f.error] || 0) + 1;
  warn('  失败原因分布：' + JSON.stringify(byReason, null, 2));
  warn('  这些记录会继续走 twimg 热链（sync.mjs 的降级路径），不会指向不存在的对象。');
}
log('  预览：npm run preview   ·   发布：npm run publish');
